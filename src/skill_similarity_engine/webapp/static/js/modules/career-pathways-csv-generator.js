/**
 * Career Pathways CSV Generator
 * Handles CSV formatting and generation for Career Pathways exports
 * 
 * Generates comprehensive CSV reports with multiple sections:
 * - Report metadata and configuration
 * - Tree structure and pathways
 * - Skills analysis (when available)
 * - Workforce context (when available)
 */

window.SkillEngine = window.SkillEngine || {};

SkillEngine.CareerPathwaysCSVGenerator = {

    /**
     * Generate comprehensive CSV content
     */
    generateCSV(exportData) {
        console.log('📝 Generating Career Pathways CSV...');

        const lines = [];
        const addLine = (content) => lines.push(content);
        const addSection = (title) => {
            addLine('');
            addLine(`"=== ${title} ==="`);
        };

        // Header
        addLine('"Career Pathways Analysis Report"');
        addLine(`"Generated: ${exportData.timestamp.toLocaleString()}"`);
        addLine(`"Export Type: ${exportData.exportType}"`);
        addLine('');

        // Report Metadata
        this.generateMetadataSection(exportData, addLine, addSection);

        // Selected Jobs
        this.generateSelectedJobsSection(exportData, addLine, addSection);

        // Tree Configuration
        this.generateConfigurationSection(exportData, addLine, addSection);

        // Organizational Filters
        this.generateFiltersSection(exportData, addLine, addSection);

        // Tree Structure
        this.generateTreeStructureSection(exportData, addLine, addSection);

        // Career Pathways
        this.generateCareerPathwaysSection(exportData, addLine, addSection);

        // Skills Analysis (conditional)
        this.generateSkillsAnalysisSection(exportData, addLine, addSection);

        // Defining Skills Analysis (conditional)
        this.generateDefiningSkillsSection(exportData, addLine, addSection);

        // Workforce Context (conditional)
        this.generateWorkforceContextSection(exportData, addLine, addSection);

        // Career Progression Trail (conditional)
        this.generateProgressionTrailSection(exportData, addLine, addSection);

        // Critical Skill Gaps Analysis (for career transitions)
        this.generateSkillGapsAnalysisSection(exportData, addLine, addSection);

        // Footer
        addLine('');
        addLine('"Report generated by NAB Skills Intelligence Platform"');
        addLine(`"Career Pathway Explorer - ${window.location.href}"`);

        console.log('✅ CSV generated successfully');
        return lines.join('\n');
    },

    /**
     * Generate metadata section
     */
    generateMetadataSection(data, addLine, addSection) {
        addSection('REPORT METADATA');
        addLine('"Field","Value"');
        addLine(`"Export Date","${data.timestamp.toISOString()}"`);
        addLine(`"Export Type","${data.exportType}"`);
        addLine(`"Jobs Selected","${data.selectedJobs.length}"`);
        addLine(`"Tree Status","${data.treeStructure.totalNodes > 0 ? 'Built' : 'Not Built'}"`);
        addLine(`"Skills Analysis Available","${data.skillsAnalysis.isAvailable ? 'Yes' : 'No'}"`);
        addLine(`"Workforce Context Available","${data.workforceContext.isAvailable ? 'Yes' : 'No'}"`);
    },

    /**
     * Generate selected jobs section
     */
    generateSelectedJobsSection(data, addLine, addSection) {
        if (data.selectedJobs.length > 0) {
            addSection('SELECTED JOBS');
            addLine('"Job ID","Job Title","Job Family","Management Group"');
            data.selectedJobs.forEach(job => {
                addLine(`"${job.id}","${job.title}","${job.family}","${job.group}"`);
            });
        } else {
            addSection('SELECTED JOBS');
            addLine('"No jobs selected"');
        }
    },

    /**
     * Generate configuration section
     */
    generateConfigurationSection(data, addLine, addSection) {
        addSection('TREE CONFIGURATION');
        addLine('"Parameter","Value"');
        addLine(`"Similarity Threshold","${data.treeConfiguration.similarityThreshold}"`);
        addLine(`"Tree Depth","${data.treeConfiguration.treeDepth}"`);
        addLine(`"Results Per Level","${data.treeConfiguration.resultsPerLevel}"`);
        addLine(`"Similarity Method","${data.treeConfiguration.similarityMethod}"`);
    },

    /**
     * Generate filters section
     */
    generateFiltersSection(data, addLine, addSection) {
        addSection('ORGANIZATIONAL FILTERS');
        addLine('"Filter Type","Value"');
        addLine(`"Division","${data.organizationalFilters.division}"`);
        addLine(`"Business Unit","${data.organizationalFilters.businessUnit}"`);
        addLine(`"Location","${data.organizationalFilters.location}"`);
        addLine(`"Region","${data.organizationalFilters.region}"`);
    },

    /**
     * Generate tree structure section
     */
    generateTreeStructureSection(data, addLine, addSection) {
        addSection('TREE STRUCTURE SUMMARY');
        addLine('"Metric","Value"');
        addLine(`"Total Nodes","${data.treeStructure.totalNodes}"`);
        addLine(`"Maximum Depth","${data.treeStructure.maxDepth}"`);

        if (data.treeStructure.nodes.length > 0) {
            addSection('TREE NODES DETAIL');
            addLine('"Node ID","Job Title","Job Function","Similarity","Depth","Parent ID","Node Type","Has Children","Is Expanded"');
            data.treeStructure.nodes.forEach(node => {
                addLine(`"${node.id}","${node.title}","${node.jobFunction}","${node.similarity}","${node.depth}","${node.parentId || 'Root'}","${node.nodeType}","${node.hasChildren ? 'Yes' : 'No'}","${node.isExpanded ? 'Yes' : 'No'}"`);
            });
        } else {
            addSection('TREE NODES DETAIL');
            addLine('"No tree structure available - build tree to see node details"');
        }
    },

    /**
     * Generate career pathways section
     */
    generateCareerPathwaysSection(data, addLine, addSection) {
        if (data.careerPathways.length > 0) {
            addSection('CAREER PATHWAYS');
            addLine('"From Job","From Job ID","To Job","To Job ID","Job Function","Basic Similarity","Enhanced Similarity"');
            data.careerPathways.forEach(pathway => {
                addLine(`"${pathway.fromJob}","${pathway.fromJobId}","${pathway.toJob}","${pathway.toJobId}","${pathway.jobFunction}","${pathway.similarity}","${pathway.enhancedSimilarity}"`);
            });
        } else {
            addSection('CAREER PATHWAYS');
            addLine('"No pathway data available - select jobs and build tree to see pathways"');
        }
    },

    /**
     * Generate skills analysis section
     */
    generateSkillsAnalysisSection(data, addLine, addSection) {
        addSection('SKILLS ANALYSIS');
        
        if (data.skillsAnalysis.isAvailable) {
            addLine('"Metric","Value"');
            addLine(`"Skills Matched","${data.skillsAnalysis.skillsMatched}"`);
            addLine(`"Skills Unique to Target","${data.skillsAnalysis.skillsUnique}"`);
            addLine(`"Defining Skills Match","${data.skillsAnalysis.definingSkillsMatch}"`);
            addLine(`"Role Similarity","${data.skillsAnalysis.roleSimilarity}"`);
        } else {
            addLine('"Status","Not Available"');
            addLine('"Note","Click on a tree node to see detailed skills analysis between roles"');
        }
    },

    /**
     * Generate defining skills section
     */
    generateDefiningSkillsSection(data, addLine, addSection) {
        addSection('DEFINING SKILLS ANALYSIS');
        
        if (data.definingSkillsAnalysis.isAvailable) {
            addLine('"Metric","Value"');
            addLine(`"Shared Defining Skills","${data.definingSkillsAnalysis.sharedSkills}"`);
            addLine(`"Unique to Target","${data.definingSkillsAnalysis.uniqueToTarget}"`);

            if (data.definingSkillsAnalysis.skillsBreakdown.length > 0) {
                addLine('');
                addLine('"=== DEFINING SKILLS BREAKDOWN ==="');
                addLine('"Skill Name","Category","Status"');
                data.definingSkillsAnalysis.skillsBreakdown.forEach(skill => {
                    addLine(`"${skill.skillName}","${skill.category}","${skill.status}"`);
                });
            }
        } else {
            addLine('"Status","Not Available"');
            addLine('"Note","Click on a tree node to see defining skills analysis"');
        }
    },

    /**
     * Generate workforce context section
     */
    generateWorkforceContextSection(data, addLine, addSection) {
        addSection('WORKFORCE CONTEXT');
        
        if (data.workforceContext.isAvailable) {
            addLine('"Metric","Value"');
            addLine(`"Total Positions","${data.workforceContext.totalPositions}"`);
            addLine(`"Divisions Represented","${data.workforceContext.divisionsRepresented}"`);
            addLine(`"Locations Spread","${data.workforceContext.locationsSpread}"`);

            if (data.workforceContext.organizationalDistribution.length > 0) {
                addLine('');
                addLine('"=== ORGANIZATIONAL DISTRIBUTION ==="');
                addLine('"Division","Business Unit","Location","Total Positions"');
                data.workforceContext.organizationalDistribution.forEach(dist => {
                    addLine(`"${dist.division}","${dist.businessUnit}","${dist.location}","${dist.totalPositions}"`);
                });
            }
        } else {
            addLine('"Status","Not Available"');
            addLine('"Note","Click on a tree node to see workforce context for that pathway"');
        }
    },

    /**
     * Generate progression trail section
     */
    generateProgressionTrailSection(data, addLine, addSection) {
        addSection('CAREER PROGRESSION TRAIL');
        
        if (data.careerProgressionTrail.isAvailable && data.careerProgressionTrail.steps.length > 0) {
            addLine('"Step","Job Title","Selected"');
            data.careerProgressionTrail.steps.forEach(step => {
                addLine(`"${step.stepNumber}","${step.jobTitle}","${step.isSelected ? 'Yes' : 'No'}"`);
            });
        } else {
            addLine('"Status","No Progression Trail"');
            addLine('"Note","Click through tree nodes to create a progression trail"');
        }
    },

    /**
     * Generate Skill Gaps Analysis section
     * This is critical for understanding what skills need development for career transitions
     */
    generateSkillGapsAnalysisSection(exportData, addLine, addSection) {
        const skillGaps = exportData.skillGapsAnalysis;
        
        if (skillGaps && skillGaps.length > 0) {
            addSection('SKILL GAPS ANALYSIS - CAREER TRANSITIONS');
            addLine('"From Job","To Job","Similarity","Transition Difficulty","Skills Already Have","Skills Need to Develop","Defining Skills Gap"');
            
            skillGaps.forEach(gap => {
                const skillsAlreadyHave = gap.skillsAlreadyHave.map(skill => 
                    skill.isDefining ? `${skill.name} (Defining)` : skill.name
                ).join('; ');
                
                const skillsNeedToDevelop = gap.skillsNeedToDevelop.map(skill => 
                    skill.isDefining ? `${skill.name} (Defining - ${skill.priority})` : `${skill.name} (${skill.priority})`
                ).join('; ');
                
                const definingSkillsNeeded = gap.skillsNeedToDevelop.filter(skill => skill.isDefining).length;
                
                addLine(`"${gap.transition.from.title}","${gap.transition.to.title}","${(gap.similarity * 100).toFixed(1)}%","${gap.transitionDifficulty}","${skillsAlreadyHave}","${skillsNeedToDevelop}","${definingSkillsNeeded} defining skills needed"`);
            });
            
            // Summary statistics
            addLine('');
            addLine('"SKILL GAPS SUMMARY"');
            addLine('"Metric","Value"');
            addLine(`"Total Career Transitions Analyzed","${skillGaps.length}"`);
            
            const avgSimilarity = skillGaps.reduce((sum, gap) => sum + gap.similarity, 0) / skillGaps.length;
            addLine(`"Average Transition Similarity","${(avgSimilarity * 100).toFixed(1)}%"`);
            
            const difficultyCount = skillGaps.reduce((acc, gap) => {
                acc[gap.transitionDifficulty] = (acc[gap.transitionDifficulty] || 0) + 1;
                return acc;
            }, {});
            
            Object.entries(difficultyCount).forEach(([difficulty, count]) => {
                addLine(`"${difficulty} Transitions","${count}"`);
            });
            
            // Detailed skills breakdown
            addLine('');
            addLine('"DETAILED SKILLS DEVELOPMENT REQUIREMENTS"');
            addLine('"From Job","To Job","Skill Name","Category","Priority","Is Defining Skill"');
            
            skillGaps.forEach(gap => {
                gap.skillsNeedToDevelop.forEach(skill => {
                    addLine(`"${gap.transition.from.title}","${gap.transition.to.title}","${skill.name}","${skill.category}","${skill.priority}","${skill.isDefining ? 'Yes' : 'No'}"`);
                });
            });
            
        } else {
            addSection('SKILL GAPS ANALYSIS - CAREER TRANSITIONS');
            addLine('"Status","Message"');
            addLine('"No Data","No career transitions available for skill gap analysis. Build a career tree with multiple levels to see skill development requirements."');
        }
    }
};

console.log('✅ Career Pathways CSV Generator module loaded');

    def _generate_pdf_from_html(self, html_content: str, base_filename: str) -> Tuple[bool, Dict[str, Any]]:
        """Generate PDF from HTML using weasyprint or reportlab."""
        try:
            # Try weasyprint first (better HTML/CSS support)
            try:
                import weasyprint
                
                # Create temporary HTML file
                temp_html_file = os.path.join(self.temp_dir, f"{base_filename}.html")
                with open(temp_html_file, 'w', encoding='utf-8') as f:
                    f.write(html_content)
                
                # Generate PDF
                pdf_content = weasyprint.HTML(filename=temp_html_file).write_pdf()
                
                # Clean up temp file
                os.unlink(temp_html_file)
                
                return True, {
                    'content': pdf_content,
                    'content_type': 'application/pdf',
                    'filename': f"{base_filename}.pdf",
                    'format': 'PDF'
                }
                
            except ImportError:
                # Fallback to reportlab (more basic but Windows-friendly)
                return self._generate_pdf_with_reportlab(html_content, base_filename)
                
        except Exception as e:
            logger.error(f"Error generating PDF: {str(e)}", exc_info=True)
            return False, {'error': f'PDF generation failed: {str(e)}'}
    
    def _generate_word_from_html(self, html_content: str, base_filename: str) -> Tuple[bool, Dict[str, Any]]:
        """Generate Word document from HTML."""
        try:
            # Try python-docx with html2docx
            try:
                from html2docx import html2docx
                
                # Extract job information for title
                job_from = base_filename.replace('career_analysis_', '').split('_')[0]
                title = f"Career Analysis - {job_from}"
                
                print(f"🔍 HTML-to-Word conversion starting...")
                print(f"🔍 HTML content length: {len(html_content)}")
                print(f"🔍 Title: {title}")
                print(f"🔍 First 500 chars of HTML: {html_content[:500]}")
                
                # DEBUG: Check if HTML contains actual content beyond header
                if len(html_content) < 1000:
                    print(f"⚠️  WARNING: HTML content is very short ({len(html_content)} chars)")
                    print(f"🔍 FULL HTML CONTENT:\n{html_content}")
                else:
                    # Check for key content indicators
                    content_indicators = ['<h1>', '<h2>', '<h3>', '<p>', '<div', '<table', '<ul>', '<ol>']
                    found_indicators = [indicator for indicator in content_indicators if indicator in html_content.lower()]
                    print(f"🔍 Content indicators found: {found_indicators}")
                    
                    # Show more of the content to debug
                    print(f"🔍 First 1500 chars of HTML:\n{html_content[:1500]}")
                
                # Convert HTML to Word with required title parameter
                try:
                    doc_content_stream = html2docx(html_content, title=title)
                    
                    print(f"🔍 Word document generated, type: {type(doc_content_stream)}")
                    
                    # html2docx returns a BytesIO object, we need to extract the bytes
                    if hasattr(doc_content_stream, 'getvalue'):
                        doc_content = doc_content_stream.getvalue()
                        print(f"🔍 Extracted bytes from BytesIO, length: {len(doc_content)}")
                    else:
                        doc_content = doc_content_stream
                        print(f"🔍 Using content directly, type: {type(doc_content)}")
                        
                    if len(doc_content) == 0:
                        print("❌ WARNING: Document content is empty after conversion!")
                        
                except Exception as conversion_error:
                    print(f"❌ html2docx conversion failed: {conversion_error}")
                    print(f"❌ Error type: {type(conversion_error)}")
                    raise conversion_error
                
                return True, {
                    'content': doc_content,
                    'content_type': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
                    'filename': f"{base_filename}.docx",
                    'format': 'Word'
                }
                
            except ImportError:
                # Fallback: save as RTF (Rich Text Format - opens in Word)
                rtf_content = self._convert_html_to_rtf(html_content)
                
                return True, {
                    'content': rtf_content.encode('utf-8'),
                    'content_type': 'application/rtf',
                    'filename': f"{base_filename}.rtf",
                    'format': 'RTF'
                }
                
        except Exception as e:
            logger.error(f"Error generating Word document: {str(e)}", exc_info=True)
            return False, {'error': f'Word document generation failed: {str(e)}'}
    
    def _generate_pdf_with_reportlab(self, html_content: str, base_filename: str) -> Tuple[bool, Dict[str, Any]]:
        """Generate PDF using reportlab (fallback method)."""
        try:
            from reportlab.lib.pagesizes import letter, A4
            from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
            from reportlab.lib.styles import getSampleStyleSheet
            from reportlab.lib.units import inch
            from html import unescape
            import io
            
            # Create PDF buffer
            buffer = io.BytesIO()
            doc = SimpleDocTemplate(buffer, pagesize=A4)
            
            # Convert HTML to simple text content
            text_content = self._html_to_text_for_reportlab(html_content)
            
            # Create document
            styles = getSampleStyleSheet()
            story = []
            
            # Add content as paragraphs
            for line in text_content.split('\n'):
                if line.strip():
                    story.append(Paragraph(unescape(line), styles['Normal']))
                    story.append(Spacer(1, 0.1*inch))
            
            doc.build(story)
            pdf_content = buffer.getvalue()
            buffer.close()
            
            return True, {
                'content': pdf_content,
                'content_type': 'application/pdf',
                'filename': f"{base_filename}.pdf",
                'format': 'PDF'
            }
            
        except Exception as e:
            logger.error(f"Error generating PDF with reportlab: {str(e)}", exc_info=True)
            return False, {'error': f'PDF generation with reportlab failed: {str(e)}'}
    
    def _convert_html_to_rtf(self, html_content: str) -> str:
        """Convert HTML to RTF format (fallback for Word)."""
        # Simple HTML to RTF conversion
        # Remove HTML tags and convert to RTF format
        import re
        
        # Extract text content
        text_content = re.sub(r'<[^>]+>', '', html_content)
        text_content = unescape(text_content)
        
        # Create basic RTF document
        rtf_content = r"""{\rtf1\ansi\deff0 {\fonttbl {\f0 Times New Roman;}}
        \f0\fs24 """ + text_content.replace('\n', r'\par ') + r'}'
        
        return rtf_content
    
    def _html_to_text_for_reportlab(self, html_content: str) -> str:
        """Convert HTML to plain text for reportlab."""
        import re
        from html import unescape
        
        # Remove script and style elements
        html_content = re.sub(r'<(script|style)[^>]*>.*?</\1>', '', html_content, flags=re.DOTALL)
        
        # Convert headers to emphasized text
        html_content = re.sub(r'<h[1-6][^>]*>(.*?)</h[1-6]>', r'\n\1\n', html_content)
        
        # Remove HTML tags
        text_content = re.sub(r'<[^>]+>', '', html_content)
        
        # Decode HTML entities
        text_content = unescape(text_content)
        
        # Clean up whitespace
        text_content = re.sub(r'\n\s*\n', '\n\n', text_content)
        text_content = re.sub(r'[ \t]+', ' ', text_content)
        
        return text_content.strip()

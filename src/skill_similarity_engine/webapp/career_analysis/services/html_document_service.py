"""
HTML Document Service

Converts frontend-rendered HTML directly to Word/PDF documents.
This ensures 100% consistency between frontend preview and downloaded documents.
"""

from typing import Dict, Any, Tuple
import logging
import tempfile
import os
from pathlib import Path
from datetime import datetime
import re
from html import unescape

logger = logging.getLogger(__name__)

class HTMLDocumentService:
    """Service for converting frontend HTML captures to Word/PDF documents."""
    
    def __init__(self):
        """Initialize the HTML document service."""
        self.temp_dir = tempfile.gettempdir()
        logger.info("HTMLDocumentService initialized")
    
    def generate_document_from_html(self, html_content: str, output_format: str = 'pdf', 
                                  metadata: Dict[str, Any] = None) -> Tuple[bool, Dict[str, Any]]:
        """
        Generate a downloadable document from frontend HTML capture.
        
        Args:
            html_content: The HTML content captured from frontend
            output_format: Output format ('pdf' or 'word')
            metadata: Metadata about the analysis (job_from, analysis_mode, etc.)
            
        Returns:
            Tuple of (success, result_data)
        """
        try:
            if metadata is None:
                metadata = {}
            
            # Clean and prepare HTML for document conversion
            cleaned_html = self._prepare_html_for_document(html_content, metadata)
            
            # Generate filename
            job_from = metadata.get('job_from', 'unknown')
            timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
            base_filename = f"career_analysis_{job_from}_{timestamp}"
            
            # Convert to requested format
            if output_format.lower() == 'pdf':
                return self._generate_pdf_from_html(cleaned_html, base_filename)
            elif output_format.lower() in ['word', 'docx']:
                return self._generate_word_from_html(cleaned_html, base_filename)
            else:
                return False, {'error': f'Unsupported output format: {output_format}'}
                
        except Exception as e:
            logger.error(f"Error generating document from HTML: {str(e)}", exc_info=True)
            return False, {'error': f'Document generation failed: {str(e)}'}
    
    def _prepare_html_for_document(self, html_content: str, metadata: Dict[str, Any]) -> str:
        """
        Prepare and clean HTML content for document conversion.
        
        This method:
        1. Extracts clean content from the captured HTML
        2. Removes CSS, JavaScript, and styling
        3. Creates simple, document-friendly HTML
        4. Adds metadata header/footer
        """
        
        # Extract job information for header
        job_from = metadata.get('job_from', 'Unknown')
        analysis_mode = metadata.get('analysis_mode', 'top_matches')
        generated_date = datetime.now().strftime('%B %d, %Y')
        
        # Mode display mapping
        mode_display = {
            'top_matches': 'Discovery Analysis',
            'specific': 'Specific Transition Analysis'
        }.get(analysis_mode, analysis_mode.title())
        
        # Clean the HTML content - remove all styling and extract just text content
        print(f"🔍 Original HTML content length: {len(html_content)}")
        cleaned_content = self._extract_text_content_from_html(html_content)
        print(f"🔍 Cleaned HTML content length: {len(cleaned_content)}")
        
        if len(cleaned_content) < 100:
            print(f"⚠️  WARNING: Cleaned content is very short!")
            print(f"🔍 Cleaned content: {cleaned_content}")
        else:
            print(f"🔍 First 300 chars of cleaned content: {cleaned_content[:300]}")
        
        # Create simple HTML document without complex CSS
        complete_html = f"""
        <!DOCTYPE html>
        <html lang="en">
        <head>
            <meta charset="UTF-8">
            <title>Career Transition Analysis - {job_from}</title>
        </head>
        <body>
            <h1>Career Transition Analysis</h1>
            <p><strong>Job Profile:</strong> {job_from} | <strong>Analysis Type:</strong> {mode_display} | <strong>Generated:</strong> {generated_date}</p>
            <p><em>NAB Skills Intelligence Platform</em></p>
            <hr>
            
            {cleaned_content}
            
            <hr>
            <p><em>Generated by NAB Skills Intelligence Platform on {generated_date}</em></p>
        </body>
        </html>
        """
        
        return complete_html
    
    def _extract_text_content_from_html(self, html_content: str) -> str:
        """Extract clean text content from HTML, preserving structure but removing styling."""
        import re
        
        # Remove style tags and their content completely
        html_content = re.sub(r'<style[^>]*>.*?</style>', '', html_content, flags=re.DOTALL | re.IGNORECASE)
        
        # Remove script tags and their content
        html_content = re.sub(r'<script[^>]*>.*?</script>', '', html_content, flags=re.DOTALL | re.IGNORECASE)
        
        # Remove HTML comments
        html_content = re.sub(r'<!--.*?-->', '', html_content, flags=re.DOTALL)
        
        # Remove complex CSS classes and styling attributes
        html_content = re.sub(r'\s+class="[^"]*"', '', html_content)
        html_content = re.sub(r'\s+style="[^"]*"', '', html_content)
        html_content = re.sub(r'\s+id="[^"]*"', '', html_content)
        
        # Clean up common Tailwind/utility classes that might remain
        html_content = re.sub(r'<div[^>]*>\s*</div>', '', html_content)  # Remove empty divs
        html_content = re.sub(r'<span[^>]*>\s*</span>', '', html_content)  # Remove empty spans
        
        # Convert common HTML elements to simpler versions
        html_content = re.sub(r'<div[^>]*>', '<div>', html_content)
        html_content = re.sub(r'<span[^>]*>', '<span>', html_content)
        html_content = re.sub(r'<p[^>]*>', '<p>', html_content)
        html_content = re.sub(r'<h([1-6])[^>]*>', r'<h\1>', html_content)
        
        # Remove any remaining complex attributes
        html_content = re.sub(r'<([a-zA-Z][a-zA-Z0-9]*)\s+[^>]*>', r'<\1>', html_content)
        
        # Clean up whitespace
        html_content = re.sub(r'\n\s*\n', '\n\n', html_content)
        html_content = re.sub(r'[ \t]+', ' ', html_content)
        
        return html_content.strip()
    
    def _clean_html_content(self, html_content: str) -> str:
        """Clean HTML content for document conversion."""
        
        # Remove script tags and their content
        html_content = re.sub(r'<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>', '', html_content, flags=re.IGNORECASE)
        
        # Remove interactive elements
        interactive_patterns = [
            r'<button\b[^>]*>.*?</button>',
            r'<input\b[^>]*>',
            r'onclick="[^"]*"',
            r'onchange="[^"]*"',
            r'href="[^"]*"'
        ]
        
        for pattern in interactive_patterns:
            html_content = re.sub(pattern, '', html_content, flags=re.IGNORECASE)
        
        # Remove loading spinners and placeholders
        html_content = re.sub(r'<div[^>]*loading[^>]*>.*?</div>', '', html_content, flags=re.IGNORECASE | re.DOTALL)
        html_content = re.sub(r'<div[^>]*placeholder[^>]*>.*?</div>', '', html_content, flags=re.IGNORECASE | re.DOTALL)
        
        # Clean up extra whitespace
        html_content = re.sub(r'\s+', ' ', html_content)
        html_content = re.sub(r'>\s+<', '><', html_content)
        
        return html_content.strip()
    
